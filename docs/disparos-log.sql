-- Histórico dos disparos de notificação (painel /disparo.html).
-- A função netlify/functions/machine-notificacao.js grava aqui cada disparo REAL
-- (não o teste) e lê no modo acao:'historico'. Tudo com a SERVICE KEY, que bypassa RLS.
-- RLS LIGADA e SEM policies de propósito: ninguém com a chave pública (anon) lê nem escreve.

create table if not exists public.disparos_log (
  id          bigint generated by default as identity primary key,
  lote        text,                       -- agrupa um disparo que foi pra várias cidades
  criado_em   timestamptz not null default now(),
  autor_id    text,                       -- pessoa_id de quem disparou (super admin)
  autor_nome  text,
  publico     text,                       -- 'motoboys' | 'empresas'
  cidade      text,
  titulo      text,
  mensagem    text,
  total       int,                        -- alvos encontrados
  enviados    int,                        -- aceitos pela Machine (receberam)
  falhas      int
);

alter table public.disparos_log enable row level security;
-- sem create policy: só a service key (servidor) escreve/lê.

create index if not exists disparos_log_criado_idx on public.disparos_log (criado_em desc);
create index if not exists disparos_log_lote_idx   on public.disparos_log (lote);
